import Foundation

/// Reconstructs the license endpoint only at runtime.
/// The complete URL is not stored as a plaintext string in the app source or binary.
enum LicenseEndpoint {
    static var url: URL? {
        let encrypted: [UInt8] = [0x32, 0x2E, 0x2E, 0x2A, 0x29, 0x60, 0x75, 0x75, 0x3B, 0x2A, 0x33, 0x31, 0x3F, 0x23, 0x3E, 0x3B, 0x29, 0x32, 0x77, 0x28, 0x32, 0x20, 0x63, 0x3B, 0x23, 0x34, 0x6E, 0x74, 0x37, 0x3B, 0x34, 0x2F, 0x29, 0x74, 0x29, 0x2A, 0x3B, 0x39, 0x3F, 0x75, 0x3B, 0x2A, 0x33, 0x75, 0x36, 0x33, 0x39, 0x3F, 0x34, 0x29, 0x3F, 0x75, 0x2C, 0x3B, 0x36, 0x33, 0x3E, 0x3B, 0x2E, 0x3F]
        let plain = encrypted.map { $0 ^ 0x5A }
        return URL(string: String(bytes: plain, encoding: .utf8) ?? "")
    }
}
